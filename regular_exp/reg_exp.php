<?php

$special_chars = '!@#$%^&*()_+\-=\[\]{};:\'",.<>?\/\\|`~';

$values = [
    '123',                                      // 1. Целое число
    'fasd321',                                  // 2. Буквы и цифры (латиница)
    'привет123hello',                           // 3. Буквы и цифры (латиница + кириллица)
    'google.com',                               // 4. Домен
    'User123',                                  // 5. Имя пользователя
    'Password123',                              // 6. Пароль (буквы и цифры)
    'Pass123!@#',                               // 7. Пароль (сложный)
    '2023-01-15',                               // 8. Дата YYYY-MM-DD
    '15/01/2023',                               // 9. Дата DD/MM/YYYY
    '15.01.2023',                               // 10. Дата DD.MM.YYYY
    '23:59:59',                                 // 11. Время HH:MM:SS
    '23:59',                                    // 12. Время HH:MM
    'http://yandex.ru/',                        // 13. URL
    'user@maildomain.com',                      // 14. E-mail
    '94.137.192.81',                            // 15. IPv4
    '2001:0:9d38:6abd:c70:2d3c:a176:3398',      // 16. IPv6
    'ec:23:3d:1b:7a:e7',                        // 17. Mac-адрес
    '+79021234567',                             // 18. Российский мобильный
    '4048 4323 9889 3301',                      // 19. Номер кредитной карты
    '380870115601',                             // 20. ИНН (12 цифр)
    '664000',                                   // 21. Почтовый индекс
    '2546,10 руб.',                             // 22. Цена в рублях
    '$39.99'                                    // 23. Цена в долларах
];

$patterns = [
    '/^[+-]?\d+$/',                                               // 1. Целое число
    '/^[a-zA-Z0-9]+$/',                                           // 2. Набор из букв и цифр (латиница)
    '/^[a-zA-Zа-яёА-ЯЁ0-9]+$/u',                                  // 3. Набор из букв и цифр (лат + кир)
    '/^([a-z0-9]+(-[a-z0-9]+)*\.)+[a-z]{2,}$/i',                  // 4. Домен
    '/^[a-zA-Z][a-zA-Z0-9]{2,24}$/',                              // 5. Имя пользователя (3-25 симв, первый - буква)
    '/^[a-zA-Z0-9]+$/',                                           // 6. Пароль (буквы и цифры)
    '/^[a-zA-Z0-9' . preg_quote($special_chars, '/') . ']{8,}$/', // 7. Пароль (мин. 8 симв + спецсимволы)
    '/^\d{4}-(0[1-9]|1[0-2])-(0[1-9]|[12]\d|3[01])$/',            // 8. Дата YYYY-MM-DD
    '/^(0[1-9]|[12]\d|3[01])\/(0[1-9]|1[0-2])\/\d{4}$/',          // 9. Дата DD/MM/YYYY
    '/^(0[1-9]|[12]\d|3[01])\.(0[1-9]|1[0-2])\.\d{4}$/',          // 10. Дата DD.MM.YYYY
    '/^([01]\d|2[0-3]):[0-5]\d:[0-5]\d$/',                        // 11. Время HH:MM:SS
    '/^([01]\d|2[0-3]):[0-5]\d$/',                                // 12. Время HH:MM
    '/^https?:\/\/[^\s\/$.?#].[^\s]*$/i',                         // 13. URL
    '/^[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}$/i',                 // 14. E-mail
    '/^((25[0-5]|(2[0-4]|1\d|[1-9]|)\d)\.?\b){4}$/',              // 15. IPv4
    '/^([0-9a-fA-F]{1,4}:){7}[0-9a-fA-F]{1,4}$/',                 // 16. IPv6
    '/^([0-9a-fA-F]{2}[:]){5}[0-9a-fA-F]{2}$/',                   // 17. Mac-адрес
    '/^\+79\d{9}$/',                                              // 18. Российский мобильный
    '/^\d{4} \d{4} \d{4} \d{4}$/',                                // 19. Кредитная карта
    '/^(\d{10}|\d{12})$/',                                        // 20. ИНН
    '/^\d{6}$/',                                                  // 21. Почтовый индекс
    '/^\d+(,\d{2})? руб\.$/u',                                    // 22. Цена руб.
    '/^\$\d+(\.\d{2})?$/'                                         // 23. Цена долл.
];

$length = min(count($values), count($patterns));

for ($i = 0; $i < $length; $i++) {
    $num = $i + 1;
    if (preg_match($patterns[$i], $values[$i])) {
        echo "$num pattern Matched!";
    } else {
        echo "$num pattern Mismatched";
    }
    echo '<br>';
}